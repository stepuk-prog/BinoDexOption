# 30 → 45 (2026-08-15): собственный бюджет ретраев pyrofork на КОННЕКТ — 3×TCP.TIMEOUT(10с) +
# 2×sleep(1с) = 32с, т.е. прежние 30с срубали библиотеку посреди её же попыток. Session.start()
# крутит `while True` и сам не сдаётся — ограничивает только наш wait_for. Переиспользуемая
# media-сессия (classes/upload_session) убирает коннект из горячего пути, но ПЕРВЫЙ аплоад после
# старта всё равно его делает: при потерях ~50% он в 30с мог не уложиться. 45с — страховка именно
# на холодный старт; выше не берём, чтобы пост 1m-экземпляра не протух в ожидании.
TG_SEND_TIMEOUT = 45          # Прямая отправка фото в канал (send_photo вне _try_send)
# 30 → 45 (2026-08-15): под этим потолком живут ровно те ветки, где соединение поднимается
# ЗАНОВО — повтор после таймаута (media-сессии ещё нет), restart клиента и resend после него,
# повтор после FloodWait. Им нужен тот же бюджет на коннект, что и первой отправке, иначе
# лечение срубается ровно там, где болезнь. Худший путь одного поста при этом — 45 (отправка)
# + 15 (проба истории) + 45 (повтор) = 105с; для 1m-экземпляра это дольше цикла, но провал
# отправки уводит в exit_main, т.е. цена альтернативы — рестарт с переподъёмом Firefox.
TG_RECONNECT_TIMEOUT = 45     # restart + повторная отправка при «Connection lost»
# Таймаут-на-отправке — НЕ доказательство недоставки: send_photo мог доехать, а ответ
# потеряться. Перед повтором заглядываем в историю канала (2026-08-15): нашли свой пост —
# считаем доставленным (и отдаём его message_id для форум-форварда), не нашли — повторяем.
TG_HISTORY_PROBE_TIMEOUT = 15  # Потолок на пробу истории канала (лёгкий вызов по ОСНОВНОЙ сессии)
# 5 → 20 (2026-08-15): один цикл кладёт в канал до 13 постов (первое/второе/итоговое +
# каскад догонов + вехи серии плюсов), а между сбоем и пробой проходит TG_SEND_TIMEOUT
# плюс restart — искомый пост успевал уехать из хвоста, проба возвращала None и канал
# получал ДУБЛЬ, ровно тот, против которого проба и заведена. Вызов по-прежнему один.
TG_HISTORY_PROBE_LIMIT = 20    # Сколько последних сообщений канала смотреть в пробе
# Проба смотрит ТОЛЬКО сообщения свежее начала своей отправки: подпись сама по себе не
# уникальна — у баг-картинки (main_bug_message) текст статический, и без окна проба нашла бы
# ПРОШЛОЕ такое же сообщение и решила, что пост доставлен. Допуск — на расхождение часов ноды
# и Telegram (message.date приходит от сервера; naive local — datetime.fromtimestamp без tz).
TG_HISTORY_PROBE_SKEW = 10     # Секунд допуска к моменту начала отправки

# Шаг graceful-завершения (закрытие браузера / стоп юзербота) — чтобы зависший
