# Коды выхода процесса — их читает диспетчер (WD/systemd) и принимает решения. ВАЖНО (инвариант):
# programdata.status=false (write_status_offline) выставляет ТОЛЬКО плановый weekend-выход binary;
# сбойные коды ниже status НЕ трогают — диспетчер сам решает по коду.
#   0  — штатная остановка извне (SIGTERM/SIGINT): диспетчер ничего не делает;
#   1  — непредвиденный краш: рестарт;
#   10 — браузер не поднялся BROWSER_MAX_ATTEMPTS раз подряд → failover на другую ноду;
#   11 — куки протухли и авто-релогин (RECOVER_ATTEMPTS) не помог;
#   12 — ДВЕ причины: (а) апп-шелл смонтирован, а нашего селектора нет → сменились селекторы
#        binodex, нужен человек (SETUP_ATTEMPTS ретраев и выход); (б) front-end binodex не
#        монтируется, и это не преодолено ни direct, ни прокси за SETUP_OUTAGE_MAX_CYCLES
#        циклов → аутэйдж устойчив С ЭТОЙ НОДЫ, отдаём её на провайдер-диверсный перенос;
#   13 — отвал session Pyrogram-юзербота → реавторизация (scripts/reauth_userbot.py).
#
# Как их читает диспетчер (Dispatcher2.0/common/schemas.py, сверено 2026-08-17):
#   • 11 и 12 — PROVIDER_SENSITIVE: сначала провайдер-диверсный перенос (сайт/куки могут не
#     работать из конкретной локации), и только когда провайдеры исчерпаны — ALARM+hold;
#   • 13 — OPERATOR_ONLY: релокация бессмысленна (мёртвая session мертва на любой ноде) →
#     СРАЗУ ALARM и ручная реавторизация, без перебора нод;
#   • 10 — релокация провайдер-диверсно + degrade ноды.
# Поэтому важно не «улучшить» сбойные ветки записью status=false: для GD это перевело бы
# программу из must-run в выключенную, и авария стала бы тихой — ни переноса, ни ALARM.
